local function currentLanguage()
    local language = G_reader_settings:readSetting("language") or "en"
    return language:sub(1, 2) == "ja" and "ja" or "en"
end

return function(key, values)
    local text = STRINGS[currentLanguage()][key] or STRINGS.en[key]
    if not values then
        return text
    end
    return (text:gsub("{{(%w+)}}", function(name) return tostring(values[name]) end))
end
